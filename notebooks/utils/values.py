"""The numbers the manuscript's text cites, formatted as printed, and their file.

Each figure cell of ``manuscript_figures.py`` returns a section of named strings; the
last cell writes them all to ``manuscript/values.toml``, which ``main.typ`` reads
(``#v("section.key")``), so the text never holds a number typed by hand that a
re-run could change. Negative numbers carry a true minus sign, ranges an en dash.
"""

from pathlib import Path

MINUS = "−"


def num(x: float, digits: int = 2) -> str:
    """*x* to *digits* decimals, with a true minus sign (and no ``-0``)."""
    text = f"{x:.{digits}f}"
    if text.startswith("-") and float(text) == 0:
        text = text[1:]
    return text.replace("-", MINUS)


def signed(x: float, digits: int = 1) -> str:
    """*x* with its sign always shown: ``+0.2``, ``−16.0``."""
    text = num(x, digits)
    return text if text.startswith(MINUS) else f"+{text}"


def count(n: float) -> str:
    """A whole number with thousands separators: ``1,519,650``."""
    return f"{round(n):,}"


def pct(share: float, digits: int = 0) -> str:
    """A share (0–1) as a percentage, without the sign: ``0.794`` -> ``79``."""
    return num(100 * share, digits)


def span(low: float, high: float, digits: int = 2) -> str:
    """A range or interval: ``0.94–0.97``; ``−0.01 to 0.04`` once a bound is negative,
    where a dash would read as a minus."""
    a, b = num(low, digits), num(high, digits)
    if a == b:
        return a
    return f"{a} to {b}" if MINUS in a + b else f"{a}–{b}"


def write(path: Path, sections: dict[str, dict[str, str]], source: str) -> None:
    """*sections* (name -> key -> printed string) as TOML, sorted, with a header
    naming the *source* that writes it."""
    lines = [f"# Generated by {source}; do not edit by hand.", ""]
    for name in sorted(sections):
        lines.append(f"[{name}]")
        for key in sorted(sections[name]):
            value = str(sections[name][key]).replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'{key} = "{value}"')
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")
